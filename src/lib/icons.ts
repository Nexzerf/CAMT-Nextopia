export type IconName = keyof typeof I;
export const ICONS: Record<IconName, readonly string[]> = I;
export const ICON_NAMES = Object.keys(I) as IconName[];

/** วาดไอคอนลง canvas 2D ที่ตำแหน่ง (x, y) ขนาดพิกเซลละ scale */
export function drawIcon(ctx: CanvasRenderingContext2D, name: IconName, x: number, y: number, scale: number) {
  const rows = ICONS[name];
  rows.forEach((row, py) => {
    for (let px = 0; px < row.length; px++) {
      const ch = row[px];
      const col = PAL[ch];
      if (!col) continue;
      ctx.fillStyle = col;
      ctx.fillRect(x + px * scale, y + py * scale, scale, scale);
    }
  });
}

const canvasCache = new Map<string, HTMLCanvasElement>();
export function iconCanvas(name: IconName, scale = 1): HTMLCanvasElement {
  const key = `${name}@${scale}`;
  let c = canvasCache.get(key);
  if (!c) {
    c = document.createElement("canvas");
    c.width = c.height = ICON_SIZE * scale;
    const ctx = c.getContext("2d")!;
    drawIcon(ctx, name, 0, 0, scale);
    canvasCache.set(key, c);
  }
  return c;
}

const urlCache = new Map<IconName, string>();
/** data URL ขนาดจริง 16×16 (ขยายด้วย CSS image-rendering: pixelated) */
export function iconUrl(name: IconName): string {
  let u = urlCache.get(name);
  if (!u) {
    u = iconCanvas(name, 1).toDataURL();
    urlCache.set(name, u);
  }
  return u;
}
